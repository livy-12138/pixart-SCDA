#!/usr/bin/env python3
"""Paired figure: frozen baseline vs Token-pair SCDA at identical seeds.

Both methods are generated by the same script with per-image deterministic
seeds derived from (base seed, category index, prompt index, repeat), so
`<prompt>_<idx>.png` is the same noise for both methods -- the pair differs only
in the model.

Cases are selected by the actual per-image BLIP-VQA score drop, NOT by eye:
the rows are the prompts where Token-pair loses the most, plus one row where
the two are close, so the figure is not a cherry-pick of extremes alone.  The
selection rule is printed in the caption.

Writes an index JSON alongside the PNG recording prompt, source files and both
scores, so every panel is traceable.
"""
import json
import sys
from pathlib import Path

ROOT = Path('/root/private_data/PixArt-alpha-attentiongate')
sys.path.insert(0, str(ROOT))

import csv

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from PIL import Image

FONT = ROOT / 'results/_work/fonts/NotoSansCJKsc-Regular.otf'
if FONT.exists():
    from matplotlib import font_manager as fm
    fm.fontManager.addfont(str(FONT))
    plt.rcParams['font.sans-serif'] = ['Noto Sans CJK SC']
plt.rcParams['axes.unicode_minus'] = False

CB_IMG = Path('/root/compbench_work/images')
CB_RES = Path('/root/compbench_work/results')
OUT = ROOT / 'results/visualization'


def per_prompt(method, category):
    path = CB_RES / method / category / 'per_prompt.csv'
    scores = {}
    if not path.exists():
        return scores
    for row in csv.DictReader(path.open()):
        if row.get('status') != 'ok':
            continue
        scores[int(row['prompt_index'])] = float(row['prediction'])
    return scores


def image_path(method, category, prompt, index):
    return CB_IMG / method / category / f'{prompt}_{index * 10:06d}.png'


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('--top', type=int, default=5)
    args = ap.parse_args()

    # --- pick cases by measured score drop -----------------------------------
    cases = []
    for category in ('color', 'texture', 'shape'):
        base = per_prompt('frozen', category)
        tp = per_prompt('tokenpair', category)
        keys = sorted(set(base) & set(tp))
        ranked = sorted((tp[k] - base[k], k) for k in keys)
        prompt_of = {}
        for row in csv.DictReader((CB_RES / 'frozen' / category / 'per_prompt.csv').open()):
            prompt_of[int(row['prompt_index'])] = row['prompt']
        for drop, k in ranked[:2]:
            cases.append((category, k, prompt_of[k], base[k], tp[k]))

    # Control row: a case where BOTH succeed and the gap is smallest, so the
    # figure is not composed only of extreme failures.  Restricting to
    # base >= 0.8 and tp >= 0.8 avoids picking a "both failed" case, which would
    # look like agreement but says nothing about the failure mode.
    category = 'color'
    base, tp = per_prompt('frozen', category), per_prompt('tokenpair', category)
    keys = sorted(set(base) & set(tp))
    both_ok = [(abs(tp[k] - base[k]), k) for k in keys if base[k] >= 0.8 and tp[k] >= 0.8]
    neutral = min(both_ok)
    prompt_of = {}
    for row in csv.DictReader((CB_RES / 'frozen' / category / 'per_prompt.csv').open()):
        prompt_of[int(row['prompt_index'])] = row['prompt']
    cases.append((category, neutral[1], prompt_of[neutral[1]],
                  base[neutral[1]], tp[neutral[1]], True))

    rows = []
    for case in cases:
        neutral_flag = case[5] if len(case) > 5 else False
        category, k, prompt, base_s, tp_s = case[:5]
        rows.append(dict(category=category, index=k, prompt=prompt,
                         baseline_score=round(base_s, 4), tokenpair_score=round(tp_s, 4),
                         delta=round(tp_s - base_s, 4), neutral_control=neutral_flag,
                         baseline_image=str(image_path('frozen', category, prompt, k)),
                         tokenpair_image=str(image_path('tokenpair', category, prompt, k))))

    n = len(rows)
    fig, axes = plt.subplots(n, 2, figsize=(9.4, 2.9 * n))
    if n == 1:
        axes = axes[None, :]
    for i, r in enumerate(rows):
        for j, (key, label) in enumerate((('baseline_image', '冻结 PixArt-α（基线）'),
                                          ('tokenpair_image', 'Token-pair SCDA'))):
            ax = axes[i, j]
            p = Path(r[key])
            if p.exists():
                ax.imshow(Image.open(p).convert('RGB'))
            else:
                ax.text(0.5, 0.5, 'missing', ha='center', va='center')
            ax.set_xticks([]); ax.set_yticks([])
            for s in ax.spines.values():
                s.set_linewidth(0.8)
            score = r['baseline_score'] if j == 0 else r['tokenpair_score']
            ax.set_xlabel(f'BLIP-VQA = {score:.3f}', fontsize=10)
        tag = '　【对照：两边都成功】' if r.get('neutral_control') else ''
        axes[i, 0].text(0.0, 1.045,
                        f"{r['prompt']}　[{r['category']}]　Δ = {r['delta']:+.3f}{tag}",
                        transform=axes[i, 0].transAxes, ha='left', va='bottom',
                        fontsize=10)
    fig.suptitle('冻结基线 vs Token-pair SCDA：同一提示词、同一随机噪声',
                 fontsize=13.5, y=0.998)
    # Column headers as figure-level text so they sit above the whole grid and
    # cannot collide with the first row's prompt label.
    fig.text(0.295, 0.9885, '冻结 PixArt-α（基线）', ha='center', va='top', fontsize=12)
    fig.text(0.755, 0.9885, 'Token-pair SCDA', ha='center', va='top', fontsize=12)
    fig.tight_layout(rect=(0, 0, 1, 0.984), h_pad=2.6)
    OUT.mkdir(parents=True, exist_ok=True)
    png = OUT / 'fig_paired_tokenpair_vs_baseline.png'
    fig.savefig(png, dpi=140)
    print('wrote', png)

    index = dict(
        description=('Paired frozen baseline vs Token-pair SCDA generations. Both use the '
                     'same per-image deterministic noise (same prompt, same seed), so a pair '
                     'differs only in the model. Scores are the per-image T2I-CompBench++ '
                     'BLIP-VQA values from the same evaluation run.'),
        selection=('Rows 1-6: the two largest per-image score drops in each of color / '
                   'texture / shape. Last row: the closest-to-equal case in color, included '
                   'so the figure is not composed only of extreme failures.'),
        protocol=('300 prompts per category, 1 image per prompt, 512x512, DPM-Solver 20 steps, '
                  'CFG 4.0, official T2I-CompBench++ evaluators'),
        caveat=('BLIP-VQA is a proxy for attribute presence, not a recognition accuracy.'),
        panels=rows)
    (OUT / 'fig_paired_tokenpair_vs_baseline.json').write_text(
        json.dumps(index, indent=2, ensure_ascii=False), encoding='utf-8')
    print('wrote', OUT / 'fig_paired_tokenpair_vs_baseline.json')
    for r in rows:
        print(f"  [{r['category']:<8}] Δ={r['delta']:+.3f}  {r['prompt']}")


if __name__ == '__main__':
    main()
